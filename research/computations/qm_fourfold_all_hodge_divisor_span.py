from collections import defaultdict
from fractions import Fraction
from itertools import combinations_with_replacement
from math import comb

def wedge(a,b):
    z=defaultdict(int)
    for x,c in a.items():
        for y,d in b.items():
            word=x+y
            if len(set(word))!=len(word):
                continue
            s=(-1)**sum(word[i]>word[j]
                       for i in range(len(word))
                       for j in range(i+1,len(word)))
            z[tuple(sorted(word))]+=s*c*d
    return {k:v for k,v in z.items() if v}

def rank(vectors):
    pivots={}
    for vector in vectors:
        v={k:Fraction(c) for k,c in vector.items() if c}
        while v:
            p=min(v)
            if p not in pivots:
                leading=v[p]
                pivots[p]={k:c/leading for k,c in v.items()}
                break
            c=v[p]
            for k,b in pivots[p].items():
                new=v.get(k,Fraction(0))-c*b
                if new:
                    v[k]=new
                else:
                    v.pop(k,None)
    return len(pivots)

def lie_action(form,kind):
    """The two generators of sl2 acting as E(f)=e and F(e)=f."""
    out=defaultdict(int)
    for indices,coef in form.items():
        for pos,index in enumerate(indices):
            if kind=="E" and index%2==1:
                new=index-1
            elif kind=="F" and index%2==0:
                new=index+1
            else:
                continue
            word=list(indices)
            word[pos]=new
            if len(set(word))<len(word):
                continue
            s=(-1)**sum(word[i]>word[j]
                       for i in range(len(word))
                       for j in range(i+1,len(word)))
            out[tuple(sorted(word))]+=coef*s
    return {k:v for k,v in out.items() if v}

def main():
    N=4
    basis=[{(k,):1} for k in range(2*N)]
    pairings=[]
    for i in range(N):
        for j in range(i,N):
            w=defaultdict(int)
            for k,v in wedge(basis[2*i],basis[2*j+1]).items():
                w[k]+=v
            for k,v in wedge(basis[2*i+1],basis[2*j]).items():
                w[k]-=v
            w={k:v for k,v in w.items() if v}
            assert lie_action(w,"E")=={}
            assert lie_action(w,"F")=={}
            pairings.append(w)
    assert len(pairings)==10
    print("10 independent Hodge (1,1) divisor tensors, sl2 E/F invariant [PASS]")
    for q in range(5):
        vectors=[]
        for ids in combinations_with_replacement(range(10),q):
            form={():1}
            for j in ids:
                form=wedge(form,pairings[j])
            if form:vectors.append(form)
        got=rank(vectors)
        upper=comb(N,q)**2-(comb(N,q+1)*comb(N,q-1)
              if 0<q<N else 0)
        assert got==upper,(q,got,upper)
        print(f"codim q={q}: exact native divisor-product rank={got}, "
              f"full rational Hodge invariant dimension={upper} [PASS]")
    print("PASS: all 5 rational Hodge degrees on generic quaternionic BxB generated by divisor products.")
    print("SCOPE: uses generic QM Hodge-group=SL2, not universal arbitrary X.")

if __name__=="__main__":
    main()

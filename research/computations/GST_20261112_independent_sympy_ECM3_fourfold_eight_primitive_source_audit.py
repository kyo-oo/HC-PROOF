"""Independent exact audit of actual original-X eight primitive Chow source cycles.

X=P_{E^3}(O plus L), E has CM by Z[i], h product principal polarization,
xi^2=h*xi. The eight trace-free Hermitian matrices represent ACTUAL
algebraic symmetric divisors (Appell-Humbert). O'Sullivan injectivity
on the subring generated by symmetric divisors upgrades top-degree
zero numerical pairing to actual CH^3=0.

This SymPy code INDEPENDENTLY computes all rational Gram matrices and
source-basis ranks, without using Wolfram results as inputs. The script
does not formalize the cited geometric theorems or the all-X Hodge
conjecture.
"""
import sympy as sp

I=sp.I
E=lambda a,b: sp.eye(3)[:,a]*sp.eye(3)[b,:]
traceless=[sp.diag(1,-1,0),sp.diag(1,0,-1)]
for a,b in [(0,1),(0,2),(1,2)]:
    traceless.extend([E(a,b)+E(b,a), I*(E(a,b)-E(b,a))])
ns=[sp.eye(3)]+traceless
assert len(ns)==9
assert [sp.trace(h) for h in ns]==[3]+[0]*8

T=sp.Matrix([[sp.trace(a)*sp.trace(b)-sp.trace(a*b)
              for b in ns] for a in ns])
P=sp.Matrix([[5*sp.trace(a*b) for b in traceless]
              for a in traceless])
Z=sp.zeros(9)
G=Z.row_join(T).col_join(T.row_join(T))
assert T.det()==1152
assert G.det()==-1327104
assert P[:2,:2]==sp.Matrix([[10,5],[5,10]])
assert P.det()==75000000

vectors=[]
for i in range(1,9):
    v=sp.zeros(18,1)
    v[i,0]=-3;v[9+i,0]=1
    vectors.append(v)
for i in range(9):
    v=sp.zeros(18,1)
    v[9+i,0]=1
    vectors.append(v)
v=sp.zeros(18,1);v[0,0]=1
vectors.append(v)
C=sp.Matrix.hstack(*vectors)
assert C.det()==-6561
assert C[:,:12].rank()==12
assert C.T*G*(C.T*G).inv()==sp.eye(18)

print({"original_X":"P_{E_CM^3}(O plus principal L)",
       "dim_complex":4,"Picard_rank_base":9,
       "middle_Hodge_rank":18,"primitive_Chow_rank":8,
       "NS_intersection_det":int(T.det()),
       "middle_Chow_intersection_det":int(G.det()),
       "primitive_Chow_Gram":P.tolist(),
       "primitive_Chow_det":int(P.det()),
       "eighteen_cycle_basis_det":int(C.det()),
       "original_twelve_source_rank":int(C[:,:12].rank()),
       "allPassed":True})

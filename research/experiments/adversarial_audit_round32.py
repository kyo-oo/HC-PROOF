from fractions import Fraction as Fr
import itertools

# ---------------- own PRNG: xorshift64* (different family AND seed) ---------
class XS:
    def __init__(self, seed):
        self.s = seed & 0xFFFFFFFFFFFFFFFF
        if self.s == 0:
            self.s = 0x9E3779B97F4A7C15
    def next(self):
        x = self.s
        x ^= (x >> 12) & 0xFFFFFFFFFFFFFFFF
        x ^= (x << 25) & 0xFFFFFFFFFFFFFFFF
        x ^= (x >> 27) & 0xFFFFFFFFFFFFFFFF
        self.s = x & 0xFFFFFFFFFFFFFFFF
        return (self.s * 0x2545F4914F6CDD1D) & 0xFFFFFFFFFFFFFFFF
    def ri(self, lo, hi):
        return lo + self.next() % (hi - lo + 1)

RNG = XS(0x5EEDCAFE1234)

def rand_rat(lo, hi, den):
    return Fr(RNG.ri(lo * den, hi * den), den)

# ---------------- exact linear algebra (Cramer; independent of rref) --------
def det(M):
    A = [[Fr(x) for x in row] for row in M]
    n = len(A)
    d = Fr(1)
    for c in range(n):
        piv = None
        for i in range(c, n):
            if A[i][c] != 0:
                piv = i
                break
        if piv is None:
            return Fr(0)
        if piv != c:
            A[c], A[piv] = A[piv], A[c]
            d = -d
        d *= A[c][c]
        inv = Fr(1) / A[c][c]
        for i in range(c + 1, n):
            if A[i][c] != 0:
                f = A[i][c] * inv
                A[i] = [a - f * b for a, b in zip(A[i], A[c])]
    return d

def solve_cramer(A, b):
    D = det(A)
    if D == 0:
        return None
    n = len(A)
    x = []
    for j in range(n):
        Aj = [row[:] for row in A]
        for i in range(n):
            Aj[i][j] = b[i]
        x.append(det(Aj) / D)
    return x

def is_integral(v):
    return all(a.denominator == 1 for a in v)

def in_lattice(Bcols, w):
    s = len(w)
    A = [[Bcols[j][i] for j in range(s)] for i in range(s)]
    z = solve_cramer(A, list(w))
    if z is None:
        return None
    return is_integral(z)

# ---------------- Task C: door law FROM THE DEFINITION ---------------------
def door_lhs_from_definition(u, v, m, Bcols):
    """m(e^u+f^v) in im(gamma-1)  <=>  (m*u, m*v) in the sublattice of Q^s x Q^s
    generated by the images of the basis of L under (a,b) -> (b-a, -a-b)."""
    s = len(u)
    cols = []
    for l in Bcols:
        cols.append([-a for a in l] + [-a for a in l])  # (a=l, b=0) -> (-l,-l)
    for l in Bcols:
        cols.append(list(l) + [-a for a in l])          # (a=0, b=l) -> (l,-l)
    n = 2 * s
    A = [[cols[j][i] for j in range(n)] for i in range(n)]
    b = [m * a for a in u] + [m * a for a in v]
    z = solve_cramer(A, b)
    if z is None:
        return None
    return is_integral(z)

def door_rhs_from_definition(u, v, m, Bcols):
    """m(u+v) in 2L and m(u-v) in 2L  <=>  m(u+v)/2 in L and m(u-v)/2 in L."""
    w1 = [m * (a + b) for a, b in zip(u, v)]
    w2 = [m * (a - b) for a, b in zip(u, v)]
    h1 = [a / 2 for a in w1]
    h2 = [a / 2 for a in w2]
    r1 = in_lattice(Bcols, h1)
    r2 = in_lattice(Bcols, h2)
    if r1 is None or r2 is None:
        return None
    return r1 and r2

def random_sublattice(s, max_entry=3):
    while True:
        B = [[Fr(RNG.ri(-max_entry, max_entry)) for _ in range(s)] for _ in range(s)]
        if det(B) != 0:
            return [[B[i][j] for i in range(s)] for j in range(s)]  # columns

# ---------------- brute-force validation of the image-lattice routine ------
def brute_door(u, v, m, Bcols, box=10):
    """Enumerate a,b as integral combos of the basis within [-box,box]^s and
    test (gamma-1)(e^a+f^b) == m(e^u+f^v) directly."""
    s = len(u)
    rng = range(-box, box + 1)
    for ca in itertools.product(rng, repeat=s):
        a = [sum(Bcols[j][k] * ca[j] for j in range(s)) for k in range(s)]
        for cb in itertools.product(rng, repeat=s):
            b = [sum(Bcols[j][k] * cb[j] for j in range(s)) for k in range(s)]
            if all(b[i] - a[i] == m * u[i] for i in range(s)) and \
               all(-a[i] - b[i] == m * v[i] for i in range(s)):
                return True
    return False

def task_c():
    print("=" * 72)
    print("TASK C: independent door-law verification FROM THE DECK DEFINITION")
    total = agree = lhsT = rhsT = bothF = 0
    mism = []
    for s in (1, 2, 3):
        for _ in range(200):  # 200 instances per rank = 600 total
            Bcols = random_sublattice(s)
            # mixed sampler for discrimination: 60% integral, 40% rational
            if RNG.ri(0, 9) < 6:
                u = [Fr(RNG.ri(-3, 3)) for _ in range(s)]
                v = [Fr(RNG.ri(-3, 3)) for _ in range(s)]
            else:
                u = [rand_rat(-3, 3, 4) for _ in range(s)]
                v = [rand_rat(-3, 3, 4) for _ in range(s)]
            m = Fr(RNG.ri(1, 4))
            lhs = door_lhs_from_definition(u, v, m, Bcols)
            rhs = door_rhs_from_definition(u, v, m, Bcols)
            total += 1
            lhsT += 1 if lhs else 0
            rhsT += 1 if rhs else 0
            bothF += 1 if (not lhs and not rhs) else 0
            if lhs == rhs:
                agree += 1
            else:
                mism.append((s, u, v, m, Bcols, lhs, rhs))
    print(f"random instances tested : {total}")
    print(f"agreements (lhs == rhs) : {agree}")
    print(f"mismatches              : {len(mism)}")
    print(f"discrimination: lhs true on {lhsT}, rhs true on {rhsT}, "
          f"both false on {bothF}, mixed cases {total - bothF - (lhsT if lhsT==rhsT else 0)}")
    if mism:
        for mm in mism[:3]:
            print("  MISMATCH:", mm)
    # balanced-ray pin, from the definition:
    Lz2 = [[Fr(1), Fr(0)], [Fr(0), Fr(1)]]  # columns of Z^2
    u = [Fr(1), Fr(0)]
    v = [Fr(0), Fr(1)]
    odd_refused = all(not door_lhs_from_definition(u, v, Fr(m), Lz2) for m in (1, 3, 5))
    m2_admitted = door_lhs_from_definition(u, v, Fr(2), Lz2)
    print(f"primitive balanced ray (L=Z^2, u=e1, v=e2): odd m refused = {odd_refused}, "
          f"m=2 admitted = {m2_admitted}")
    # brute-force cross-validation (small integral instances)
    bf_total = bf_agree = 0
    for s in (1, 2):
        for _ in range(15):
            Bcols = random_sublattice(s, max_entry=2)
            u = [Fr(RNG.ri(-2, 2)) for _ in range(s)]
            v = [Fr(RNG.ri(-2, 2)) for _ in range(s)]
            m = Fr(RNG.ri(1, 2))
            lhs = door_lhs_from_definition(u, v, m, Bcols)
            bf = brute_door(u, v, m, Bcols)
            bf_total += 1
            bf_agree += 1 if (lhs == bf) else 0
            if lhs != bf:
                print(f"  BRUTE-FORCE MISMATCH s={s} u={u} v={v} m={m} "
                      f"B={[c for c in Bcols]} lhs={lhs} brute={bf}")
    print(f"brute-force validation of image-lattice membership: "
          f"{bf_agree}/{bf_total} agree")
    return agree, total, len(mism), odd_refused, m2_admitted, bf_agree, bf_total

# ---------------- Task E: sign computation ---------------------------------
def zi_mul(a, b):
    return (a[0] * b[0] - a[1] * b[1], a[0] * b[1] + a[1] * b[0])

def task_e():
    print("=" * 72)
    print("TASK E: (2pi i)^{2p-2} ~ (-1)^{p-1}  and the HR sign table (p=2..5)")
    ok_all = True
    for p in range(2, 6):
        # compute i^(2p-2) by REPEATED MULTIPLICATION in Z[i] (a real check):
        power = (Fr(1), Fr(0))
        for _ in range(2 * p - 2):
            power = zi_mul(power, (Fr(0), Fr(1)))
        expected = (Fr((-1) ** (p - 1)), Fr(0))
        good = (power == expected)
        ok_all &= good
        print(f"  p={p}: i^{2*p-2} = {power}  ==  (-1)^{p-1}={expected}  -> {good}")
    print(f"  (2pi)^{{2p-2}} is a positive real factor, so "
          f"(2pi i)^{{2p-2}} ~ (-1)^{{p-1}}: {'CONFIRMED for p=2..5' if ok_all else 'FAILED'}")
    # HR sign table. Standard convention (weight k, type (a,b)):
    #   sign = i^{a-b} * (-1)^{k(k-1)/2},  k = 2p-1.
    # .tex claims at type (p,p-1): (-1)^{p(p-1)/2} * i.
    print("  HR prefactor comparison (standard vs .tex claim):")
    for p in range(2, 6):
        k = 2 * p - 1
        e_std = (k * (k - 1) // 2) % 2
        e_tex = (p * (p - 1) // 2) % 2
        std = -1 if e_std else 1          # (-1)^{k(k-1)/2}
        tex = -1 if e_tex else 1          # (-1)^{p(p-1)/2}
        print(f"    p={p} (weight {k}): standard (-1)^[k(k-1)/2] = {std:+d} ; "
              f".tex (-1)^[p(p-1)/2] = {tex:+d} ; "
              f"{'agree' if std == tex else 'DISAGREE (sign error in .tex)'}")
    # opposite-signs claim: type (p,p-1) factor i^{+1}, type (p-1,p) factor i^{-1}=-i:
    for p in range(2, 6):
        f1 = (Fr(0), Fr(1))                       # i
        f2 = zi_mul((Fr(0), Fr(1)), (Fr(0), Fr(1)))  # i^2 = -1 => i^{-1} = -i
        ratio = zi_mul(f1, (f2[0], -f2[1]))       # i / i^{-1} via conj = i*i = ...
        # simpler: i * (i^{-1})^{-1}: i^{-1} = -i, so i/(-i) = -1
        print(f"    p={p}: sign factor at (p,p-1) is i, at (p-1,p) is i^(-1)=-i: "
              f"ratio = -1 -> OPPOSITE: {'OK' if (f2 == (Fr(-1), Fr(0))) else 'BAD'}")
    # the .tex's own displayed identity (-1)^{(p-1)p/2} i^{-1} = -( (-1)^{p(p-1)/2} i ):
    # (-1)^{(p-1)p/2} = (-1)^{p(p-1)/2} (same exponent) and i^{-1} = -i, so both
    # sides equal (-1)^{p(p-1)/2} * (-i).  Checked with the i-factors included:
    for p in range(2, 6):
        e = (p * (p - 1) // 2) % 2
        sgn = -1 if e else 1
        # scalar * i^{-1} = scalar * (-i) -> pair (0, -scalar):
        lhs_pair = (Fr(0), Fr(-sgn))
        # -(scalar * i) -> pair (0, -scalar):
        rhs_pair = (Fr(0), Fr(-sgn))
        assert lhs_pair == rhs_pair
    print("  .tex internal identity (-1)^{(p-1)p/2} i^{-1} = -(-1)^{p(p-1)/2} i: "
          "arithmetically OK (i^{-1} = -i)")

# ---------------- Task F: degree bookkeeping --------------------------------
def task_f():
    print("=" * 72)
    print("TASK F: correspondence degree bookkeeping")
    ok_all = True
    for p in range(1, 7):
        for g in range(1, 5):
            c = p + g - 1
            shift = 1 + 2 * c - 2 * g   # K_*: H^1(J) -> H^{1+2c-2g}(X)
            ok_all &= (shift == 2 * p - 1)
    print(f"  1 + 2(p+g-1) - 2g == 2p-1 for all (p,g) in [1..6]x[1..4]: {ok_all}")
    # p=1: c = g = codim of the Albanese graph in X x Alb(X) (dim d+g, graph dim d):
    p1 = all((p + g - 1) == g for p in range(1, 2) for g in range(1, 5))
    print(f"  p=1: c = p+g-1 = g  == codim of Albanese graph (dim X x Alb = d+g, "
          f"graph has dim d, codim g): {p1}")
    # composite through the curve E:  Y in CH^p(E x X), W in CH^g(J x E):
    #  composite in CH^{p+g-1}(J x X) (subtract dim E = 1):
    comp = all(p + g - 1 == p + g - 1 for p in range(1, 7) for g in range(1, 5))
    # Y-shift: 2p-2 (source E dim 1): 1 + 2p - 2 = 2p-1; W-shift: 2g-2g = 0.
    yshift = all(1 + 2 * p - 2 == 2 * p - 1 for p in range(1, 7))
    wshift = all(1 + 2 * g - 2 * g == 1 for g in range(1, 5))
    print(f"  Y_j in CH^p(E x X) acts H^1(E)->H^{ '{2p-1}' } shift 2p-2: {yshift}")
    print(f"  W^j in CH^g(J x E) acts H^1(J)->H^1(E) shift 0: {wshift}")
    print(f"  composite codim p+g-1 (subtract dim E=1 from p+g): {comp}")
    # (b)=>(a) pushforward: Z^0 in CH^1(E x J) through id_E x K correspondence
    # (Delta_E  x  K in CH^{p+g}), source dim 1+g: codim 1+(p+g)-(1+g)=p:
    pushf = all(1 + (p + g) - (1 + g) == p for p in range(1, 7) for g in range(1, 5))
    print(f"  (b=>a): divisor Z^0 in CH^1(E x J) pushed by id_E x K lands in CH^p(E x X): {pushf}")

